package gno

import (
	"bytes"
	"fmt"
	"go/format"

	"github.com/gnofy-xyz/gnofy/internal/ir"
)

// emitIdiomaticGRC20 genera un Realm GRC-20 100% nativo de gno.land usando
// gno.land/p/nt/grc20/v0 (y gno.land/p/nt/ownable/v0 si el contrato tiene owner/onlyOwner).
func (g *Generator) emitIdiomaticGRC20(c *ir.Contract) ([]byte, error) {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by gnofy (--idiomatic: Solidity ERC-20 -> Gno GRC-20). Source: %s\n", c.SourcePath)
	fmt.Fprintf(&buf, "package %s\n\n", c.GoPkgName)

	buf.WriteString("import (\n")
	buf.WriteString("\t\"gno.land/p/nt/grc20/v0\"\n")
	if c.IdiomaticOwnable {
		buf.WriteString("\t\"gno.land/p/nt/ownable/v0\"\n")
	}
	buf.WriteString(")\n\n")

	buf.WriteString("var (\n")
	buf.WriteString("\tToken       *grc20.Token\n")
	buf.WriteString("\tledger      *grc20.PrivateLedger\n")
	if c.IdiomaticOwnable {
		buf.WriteString("\tOwnable     *ownable.Ownable\n")
	}
	buf.WriteString("\tinitialized bool\n")
	buf.WriteString(")\n\n")

	decimals := c.DecimalsDefault
	if decimals == 0 {
		decimals = 6
	}

	fmt.Fprintf(&buf, "// Init inicializa el token GRC-20 (equivalente al constructor ERC-20).\n")
	fmt.Fprintf(&buf, "func Init(cur realm, nameParam string, symbolParam string, initialSupply int64) {\n")
	fmt.Fprintf(&buf, "\tif initialized {\n\t\tpanic(\"%s: already initialized\")\n\t}\n", c.Name)
	buf.WriteString("\tinitialized = true\n")
	buf.WriteString("\tcaller := cur.Previous().Address()\n")
	fmt.Fprintf(&buf, "\tToken, ledger = grc20.NewToken(nameParam, symbolParam, %d, 0, cur)\n", decimals)
	if c.IdiomaticOwnable {
		buf.WriteString("\tOwnable = ownable.NewWithAddress(caller)\n")
	}
	buf.WriteString("\tif initialSupply > 0 {\n")
	buf.WriteString("\t\tcheckErr(ledger.Mint(caller, initialSupply))\n")
	buf.WriteString("\t}\n")
	buf.WriteString("}\n\n")

	// Consultas estándar GRC-20
	buf.WriteString("func Name() string {\n\tassertInit()\n\treturn Token.GetName()\n}\n\n")
	buf.WriteString("func Symbol() string {\n\tassertInit()\n\treturn Token.GetSymbol()\n}\n\n")
	buf.WriteString("func Decimals() int {\n\tassertInit()\n\treturn Token.GetDecimals()\n}\n\n")
	buf.WriteString("func TotalSupply() int64 {\n\tassertInit()\n\treturn Token.TotalSupply()\n}\n\n")
	buf.WriteString("func BalanceOf(account address) int64 {\n\tassertInit()\n\treturn Token.BalanceOf(account)\n}\n\n")
	buf.WriteString("func Allowance(owner, spender address) int64 {\n\tassertInit()\n\treturn Token.Allowance(owner, spender)\n}\n\n")

	// Operaciones estándar GRC-20
	buf.WriteString("func Transfer(cur realm, to address, amount int64) bool {\n")
	buf.WriteString("\tassertInit()\n")
	buf.WriteString("\tcheckErr(ledger.Transfer(cur.Previous().Address(), to, amount))\n")
	buf.WriteString("\treturn true\n")
	buf.WriteString("}\n\n")

	buf.WriteString("func Approve(cur realm, spender address, amount int64) bool {\n")
	buf.WriteString("\tassertInit()\n")
	buf.WriteString("\tcheckErr(ledger.Approve(cur.Previous().Address(), spender, amount))\n")
	buf.WriteString("\treturn true\n")
	buf.WriteString("}\n\n")

	buf.WriteString("func TransferFrom(cur realm, from address, to address, amount int64) bool {\n")
	buf.WriteString("\tassertInit()\n")
	buf.WriteString("\tcheckErr(ledger.TransferFrom(from, cur.Previous().Address(), to, amount))\n")
	buf.WriteString("\treturn true\n")
	buf.WriteString("}\n\n")

	if c.HasMint {
		buf.WriteString("func Mint(cur realm, to address, amount int64) {\n")
		buf.WriteString("\tassertInit()\n")
		if c.IdiomaticOwnable {
			buf.WriteString("\tOwnable.AssertOwnedBy(cur.Previous().Address())\n")
		}
		buf.WriteString("\tcheckErr(ledger.Mint(to, amount))\n")
		buf.WriteString("}\n\n")
	}

	if c.HasBurn {
		buf.WriteString("func Burn(cur realm, amount int64) {\n")
		buf.WriteString("\tassertInit()\n")
		buf.WriteString("\tcheckErr(ledger.Burn(cur.Previous().Address(), amount))\n")
		buf.WriteString("}\n\n")
	}

	if c.IdiomaticOwnable {
		buf.WriteString("func Owner() address {\n\tassertInit()\n\treturn Ownable.Owner()\n}\n\n")
		buf.WriteString("func TransferOwnership(cur realm, newOwner address) {\n")
		buf.WriteString("\tassertInit()\n")
		buf.WriteString("\tcheckErr(Ownable.TransferOwnership(0, cur, newOwner))\n")
		buf.WriteString("}\n\n")
	}

	if g.opts.GenerateRender {
		buf.WriteString("// Render expone la vista Markdown nativa del token GRC-20 en gno.land.\n")
		buf.WriteString("func Render(path string) string {\n")
		buf.WriteString("\tif !initialized || Token == nil {\n")
		fmt.Fprintf(&buf, "\t\treturn \"# %s (GRC-20)\\n\\nPendiente de inicialización (Init).\\n\"\n", c.Name)
		buf.WriteString("\t}\n")
		buf.WriteString("\treturn Token.RenderHome()\n")
		buf.WriteString("}\n\n")
	}

	buf.WriteString("func assertInit() {\n")
	fmt.Fprintf(&buf, "\tif !initialized || Token == nil {\n\t\tpanic(\"%s: not initialized\")\n\t}\n", c.Name)
	buf.WriteString("}\n\n")

	buf.WriteString("func checkErr(err error) {\n")
	buf.WriteString("\tif err != nil {\n\t\tpanic(err.Error())\n\t}\n")
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return buf.Bytes(), nil
	}
	return formatted, nil
}

// emitIdiomaticRender genera un Render(path string) string en Markdown mostrando
// una tabla viva con las variables de estado del contrato.
func (ec *emitCtx) emitIdiomaticRender(buf *bytes.Buffer) {
	fmt.Fprintf(buf, "// Render expone una vista Markdown viva del estado del Realm en gno.land.\n")
	buf.WriteString("func Render(path string) string {\n")
	fmt.Fprintf(buf, "\tout := \"# %s\\n\\n\"\n", ec.c.Name)
	if len(ec.c.StateVars) > 0 {
		buf.WriteString("\tout += \"| Campo | Valor |\\n| --- | --- |\\n\"\n")
		for _, sv := range ec.c.StateVars {
			valExpr, ok := ec.renderStateVarValue(sv)
			if !ok {
				continue
			}
			fmt.Fprintf(buf, "\tout += \"| `%s` | \" + %s + \" |\\n\"\n", sv.GoName, valExpr)
		}
	}
	buf.WriteString("\treturn out\n")
	buf.WriteString("}\n")
}

func (ec *emitCtx) renderStateVarValue(sv *ir.StateVar) (string, bool) {
	switch {
	case sv.Type.Kind == "string":
		return sv.GoName, true
	case sv.Type.Kind == "address":
		return fmt.Sprintf("string(%s)", sv.GoName), true
	case sv.Type.Kind == "bool":
		return fmt.Sprintf("%sFormatBool(%s)", ec.rtPrefix, sv.GoName), true
	case sv.Type.IsU256():
		return fmt.Sprintf("%s.String()", sv.GoName), true
	case sv.Type.Kind == "uint" || sv.Type.Kind == "enum":
		return fmt.Sprintf("%sFormatU64(uint64(%s))", ec.rtPrefix, sv.GoName), true
	case sv.Type.Kind == "int":
		return fmt.Sprintf("%sFormatI64(int64(%s))", ec.rtPrefix, sv.GoName), true
	case sv.Type.Kind == "mapping":
		return fmt.Sprintf("%sFormatU64(uint64(%s.Size())) + \" entradas\"", ec.rtPrefix, sv.GoName), true
	case sv.Type.Kind == "array":
		return fmt.Sprintf("%sFormatU64(uint64(len(%s))) + \" elementos\"", ec.rtPrefix, sv.GoName), true
	default:
		return "", false
	}
}
